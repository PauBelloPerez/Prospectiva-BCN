// Proves de l'estat de l'editor amb un DOM mínim simulat; no substitueixen una prova visual.
'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict'),E=require('../engine.js');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
const elements=Object.fromEntries(ids.map(id=>[id,{value:'',innerHTML:'',hidden:false,open:false,addEventListener(){},showModal(){this.open=true;},close(){this.open=false;}}]));
const dynamic=['editLabel','editType','editMissing','editMin','editMax','editReverse','editConfirmed'];
for(const id of dynamic)elements[id]={value:'',checked:false};
const context=vm.createContext({CEO:E,CEOReport:require('../report-export.js'),structuredClone,console,alert:msg=>{throw Error(msg);},document:{getElementById:id=>{if(!elements[id])throw Error('Unexpected DOM id: '+id);return elements[id];},addEventListener(){},querySelectorAll(){return [];}}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../app.js'),'utf8'),context);
vm.runInContext(`install({headers:['ESTUDIS_1_15','VAL_S_ILLA_0_10'],rows:[{ESTUDIS_1_15:'10',VAL_S_ILLA_0_10:'Molt deficient'},{ESTUDIS_1_15:'11',VAL_S_ILLA_0_10:'Etiqueta desconeguda'}]},'test.csv');defs.ESTUDIS_1_15.map={'10':{label:'Universitaris'},'11':{label:'Universitaris'}};optionCache.clear();editVariable('ESTUDIS_1_15');`,context);
assert.ok(elements.variableForm.innerHTML.includes('Universitaris'));
elements.resetVariable.onclick();
assert.ok(elements.variableForm.innerHTML.includes('Valors predeterminats carregats'));
assert.equal(vm.runInContext('Object.keys(variableDraft.map).length',context),0);
assert.equal(vm.runInContext('defs.ESTUDIS_1_15.map["10"].label',context),'Universitaris');
elements.variableDialog.close();
vm.runInContext("editVariable('ESTUDIS_1_15');",context);
assert.ok(elements.variableForm.innerHTML.includes('Universitaris')); // tancar cancel·la el restabliment
elements.resetVariable.onclick();
for(const [id,value] of Object.entries({editLabel:'Nivell d’estudis',editType:'category',editMissing:'98,99',editMin:'',editMax:'',editReverse:'no'}))elements[id].value=value;
elements.editConfirmed.checked=true;
elements.applyVariable.onclick();
assert.equal(vm.runInContext('Object.keys(defs.ESTUDIS_1_15.map).length',context),0);
assert.equal(vm.runInContext("opts('ESTUDIS_1_15').length",context),2);
vm.runInContext("editVariable('VAL_S_ILLA_0_10');",context);
assert.ok(elements.variableForm.innerHTML.includes('Etiqueta desconeguda (1 entrevistes)'));
assert.ok(elements.variableForm.innerHTML.includes('unrecognized-row'));
assert.ok(elements.variableForm.innerHTML.includes('value="0"'));
console.log('OK editor: reinici en esborrany, cancel·lació, aplicació i diagnòstic. DOM simulat.');
vm.runInContext("config.indicators=[{variable:'VAL_S_ILLA_0_10',stat:'mean'}];render();",context);
assert.equal(elements.wordBtn.disabled,false);
let report=vm.runInContext('reportData()',context);
assert.equal(report.tables[0].rows.find(r=>r.kind==='data').cells[1],'0,0');
assert.ok(vm.runInContext('exportHTML()',context).includes('size:A4 portrait'));
vm.runInContext("config.groups=Array.from({length:6},(_,i)=>({name:'Grup '+i,mode:'all',filters:[]}));render();",context);
report=vm.runInContext('reportData()',context);
assert.equal(report.orientation,'landscape');
assert.equal(report.tables.length,1);
elements.reportOrientation.onchange({target:{value:'portrait'}});
report=vm.runInContext('reportData()',context);
assert.equal(report.tables.length,3);
assert.ok(report.tables.every(t=>t.headers.length<=4));
assert.ok(report.tables[0].headers[3].includes('Diferència'));
assert.ok(report.tables[2].headers[1].includes('Grup 5'));
console.log('OK integració: botó Word, dades de la taula i partició vertical de sis grups. DOM simulat.');

// Exercise the actual export handlers and replacement of a loaded wave.
vm.runInContext(`install({headers:['REO','MES','ANY','EDAT'],rows:[{REO:'1200',MES:'03',ANY:'2026',EDAT:'30'}]},'wave.csv');config.indicators=[{variable:'EDAT',stat:'mean'}];render();`,context);
const metadata='REO: 1200 · MES: març · ANY: 2026';
assert.ok(elements.studyMetadata.innerHTML.includes(metadata));
assert.deepEqual(Array.from(vm.runInContext('reportData().studyLines',context)),[metadata]);
vm.runInContext('download=(data,name,type)=>{globalThis.captured={data,name,type};}',context);
elements.exportBtn.onclick();
assert.ok(context.captured.data.split('\r\n')[1].includes(metadata));
elements.htmlBtn.onclick();
assert.ok(context.captured.data.indexOf(metadata)<context.captured.data.indexOf('<table>'));
elements.wordBtn.onclick();
assert.ok(Buffer.from(context.captured.data).toString('utf8').includes(metadata));
context.Blob=Blob;
context.ClipboardItem=class {constructor(items){this.items=items;}};
let clipboard;
context.navigator={clipboard:{async write(items){clipboard=items[0].items;}}};
(async()=>{
 await elements.copyBtn.onclick();
 assert.equal((await clipboard['text/plain'].text()).split('\n')[1],metadata);
 assert.ok((await clipboard['text/html'].text()).includes(metadata));
 vm.runInContext(`globalThis.oldAnalysis={config:structuredClone(config),definitions:structuredClone(defs)};install({headers:['REO','MES','ANY','EDAT'],rows:[{REO:'1300',MES:'juny',ANY:'2027',EDAT:'40'}]},'new-wave.csv');applySaved(oldAnalysis,{});`,context);
 assert.deepEqual(Array.from(vm.runInContext('reportData().studyLines',context)),['REO: 1300 · MES: juny · ANY: 2027']);
 vm.runInContext(`install({headers:['EDAT'],rows:[{EDAT:'50'}]},'no-metadata.csv');`,context);
 assert.ok(!elements.studyMetadata.innerHTML.includes('1300'));
 assert.ok(elements.studyMetadata.innerHTML.includes('no disponible'));
 console.log('OK metadades: pantalla, CSV, HTML/PDF, Word, porta-retalls i canvi d’onada amb configuració desada.');
})().catch(error=>{console.error(error);process.exitCode=1;});
