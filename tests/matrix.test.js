'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const E=require('../engine.js'),R=require('../report-export.js');
const headers=['RECALL','DEST','CITY','WEIGHT'],defs=Object.fromEntries(headers.map(n=>[n,E.definition(n)]));
const rows=Array.from({length:8},(_,i)=>[{RECALL:'P'+i,DEST:'A',CITY:'BCN',WEIGHT:'1'},{RECALL:'P'+i,DEST:'B',CITY:'BCN',WEIGHT:'3'}]).flat();
rows.push({RECALL:'P0',DEST:'',CITY:'BCN',WEIGHT:'2'},{RECALL:'',DEST:'A',CITY:'BCN',WEIGHT:'1'},{RECALL:'Z',DEST:'A',CITY:'OTHER',WEIGHT:'1'});
const filters=[{variable:'CITY',op:'in',values:[E.decode('BCN',defs.CITY).key]}];
const grouped=E.categoryGroups(rows,'RECALL',defs,filters);
assert.equal(grouped.categories.length,8);assert.equal(grouped.total,18);assert.equal(grouped.missing,1);
assert.equal(grouped.categories.find(c=>c.label==='P0').n,3);
let config={groups:grouped.categories.map(c=>c.group),indicators:[{variable:'DEST'}],globalFilters:filters,denominator:'valid',weight:'WEIGHT'};
let result=E.analyze(rows,defs,config);
assert.equal(result.overlap,0);assert.equal(result.groups.reduce((n,g)=>n+g.n,0),17);
let p0=result.indicators[0].stats[0];assert.equal(p0.missing,1);assert.equal(p0.counts.find(c=>c.label==='A').pct,25);
result=E.analyze(rows,defs,{...config,denominator:'all'});p0=result.indicators[0].stats[0];assert.ok(Math.abs(p0.counts.find(c=>c.label==='A').pct-100/6)<1e-10);
const recoded=structuredClone(defs);recoded.RECALL.map={p0:{label:'Units'},p1:{label:'Units'}};
const combined=E.categoryGroups(rows,'RECALL',recoded,filters);
assert.equal(combined.categories.length,7);assert.equal(combined.categories.find(c=>c.label==='Units').n,5);
assert.equal(E.categoryGroups(rows,'RECALL',defs,[{variable:'CITY',op:'in',values:[]}]).categories.length,0);
assert.throws(()=>E.categoryGroups(rows,'WEIGHT',{...defs,WEIGHT:{...defs.WEIGHT,type:'number'}}));

